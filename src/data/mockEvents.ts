/**
 * SYNTHETIC DATASET — every event, host, specialist, amount, and note is fictional.
 * Nothing here comes from Wounded Warrior Project, Salesforce NPSP, or DonorDrive.
 *
 * All dates are calculated relative to DEMO_AS_OF_DATE so the boundary scenarios
 * (29 / 30 / 31 days, future, missing date, …) stay reproducible.
 */
export const DEMO_AS_OF_DATE: ISODate = '2026-11-10';

/** Date `n` days before the demo as-of date (negative `n` = in the future). */
const ago = (n: number): ISODate => addDays(DEMO_AS_OF_DATE, -n);

const RULE = 'Monitoring rule (simulated)';
const LEAD = 'Team Lead (fictional)';

function tl(id: string, entries: Array<[number, TimelineEntryType, string, string?]>): TimelineEntry[] {
  return entries.map(([daysAgo, type, description, actor], i) => ({
    id: `${id}-t${i + 1}`,
    date: ago(daysAgo),
    type,
    description,
    actor: actor ?? 'System (simulated)',
  }));
}

function note(id: string, n: number, daysAgo: number, author: string, text: string): FollowUpNote {
  return { id: `${id}-n${n}`, date: ago(daysAgo), author, text };
}

const flaggedEntry = (daysAgo: number): [number, TimelineEntryType, string, string] => [
  daysAgo,
  'review',
  'Monitoring review: $0 posted more than 30 days after the event. Flagged as Needs Review.',
  RULE,
];

